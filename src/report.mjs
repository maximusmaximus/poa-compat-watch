// Plain-English report (Markdown) for terminals, PR bodies and job summaries.
const h = (v) => (v ? `\`${String(v).slice(0, 12)}…\`` : '_unknown_');

const HEADLINE = {
  compatible: '✅ Compatible: nothing to update',
  'needs-update': '🔄 Needs update: PoA core moved, nothing this project relies on broke',
  breaking: '🚨 Breaking: the app cannot work against the current PoA core until this is updated',
};

export function renderCheck(r) {
  const L = r.live;
  const lines = [];
  lines.push(`## ${HEADLINE[r.classification] || r.classification}`);
  lines.push('');
  lines.push(`**Project:** ${r.project}  `);
  lines.push(`**Checked:** ${r.checkedAt}`);
  lines.push('');
  lines.push('| | Project | Live network |');
  lines.push('| --- | --- | --- |');
  lines.push(`| Engine | ${h(r.pinned.engine)} | ${h(L.engineSha256)} |`);
  lines.push(`| Params | ${h(r.pinned.params)} | ${h(L.paramsSha256)} |`);
  lines.push(`| Client bundle | ${h(r.pinned.client)} | ${h(L.clientSha256)} |`);
  lines.push(`| Release | ${r.pinnedRelease || '_unknown_'} | ${L.release?.version || '_unknown_'} |`);
  lines.push('');
  lines.push(`Network: ${L.chainId || '?'}, open epoch ${L.openEpoch ?? '?'}.${r.releasesBehind > 0 ? ` The project is ${r.releasesBehind} release${r.releasesBehind === 1 ? '' : 's'} behind.` : ''}`);
  lines.push('');
  lines.push('**Why:**');
  for (const x of r.reasons) lines.push(`- ${x}`);
  if (r.pinProblems?.length) { lines.push(''); lines.push('**Pin problems:**'); for (const p of r.pinProblems) lines.push(`- ${p}`); }
  lines.push('');
  lines.push(`**Client surface:** ${r.surface.state}`);
  if (r.surface.diff) lines.push('', renderDiff(r.surface.diff));
  if (L.warnings?.length) { lines.push(''); lines.push('**Notes from the network read:**'); for (const w of L.warnings) lines.push(`- ${w}`); }
  return lines.join('\n');
}

export function renderDiff(diff, { maxInfo = 25 } = {}) {
  const lines = [];
  lines.push(`Surface diff: ${diff.counts.breaking} breaking, ${diff.counts.review} to review, ${diff.counts.info} informational.`);
  const group = (sev, title, max = Infinity) => {
    const items = diff.changes.filter((c) => c.severity === sev);
    if (!items.length) return;
    lines.push('', `**${title}**`);
    for (const c of items.slice(0, max)) lines.push(`- ${c.detail}`);
    if (items.length > max) lines.push(`- …and ${items.length - max} more`);
  };
  group('breaking', '🚨 Breaking for this project');
  group('review', '👀 Worth a look');
  group('info', 'ℹ️ Other changes', maxInfo);
  return lines.join('\n');
}

export function renderUpdate(u, { autoMerge } = {}) {
  const lines = [renderCheck(u.check), ''];
  lines.push('### Changes in this update');
  if (u.changedFiles.length) for (const f of u.changedFiles) lines.push(`- \`${f}\``);
  else lines.push('- none');
  for (const n of u.notes || []) lines.push(`- note: ${n}`);
  lines.push('', '### Tests');
  if (u.tests.skipped) lines.push('- skipped');
  else if (!u.tests.configured) lines.push('- no test commands configured');
  else {
    for (const t of u.tests.results) lines.push(`- ${t.ok ? '✅' : '❌'} \`${t.run}\` (${t.seconds}s)`);
    const failed = u.tests.results.find((t) => !t.ok);
    if (failed) lines.push('', '<details><summary>Failure output (tail)</summary>', '', '```', failed.tail, '```', '', '</details>');
    const notRun = u.tests.configured - u.tests.results.length;
    if (notRun > 0) lines.push(`- ${notRun} later command${notRun === 1 ? '' : 's'} not run`);
  }
  if (autoMerge) lines.push('', '### Merge', autoMerge);
  lines.push('', '_Generated by poa-compat. Values come from the public network facts, release manifest and client bundle._');
  return lines.join('\n');
}
