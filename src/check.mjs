// check / update orchestration.
import fs from 'node:fs';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { readLive, liveSummary, releasesSince, releasesForEngine } from './live.mjs';
import { readPins, pinnedValues, writePins } from './pins.mjs';
import { extractSurface } from './surface.mjs';
import { compareSurfaces, checkExpectations } from './compare.mjs';
import { redact } from './redact.mjs';

export const EXIT = Object.freeze({ COMPATIBLE: 0, ERROR: 1, UNAVAILABLE: 2, TESTS_FAILED: 3, NEEDS_UPDATE: 10, BREAKING: 20 });
const HEX64 = /^[0-9a-f]{64}$/;

export function readSnapshot(cfg) {
  if (!cfg.surface) return null;
  const f = path.join(cfg.root, cfg.surface.snapshot);
  if (!fs.existsSync(f)) return null;
  return JSON.parse(fs.readFileSync(f, 'utf8'));
}

export function makeSnapshot(live, surface) {
  return {
    note: 'Generated by poa-compat. Structural surface of the PoA client bundle this project was last checked against.',
    capturedAt: live.fetchedAt,
    chainId: live.chainId,
    engineSha256: live.engineSha256,
    paramsSha256: live.paramsSha256,
    clientSha256: live.client?.sha256 ?? null,
    clientSize: live.client?.size ?? null,
    releaseVersion: live.release?.version ?? null,
    factsKeys: live.facts?.keys ?? [],
    statusKeys: live.status?.keys ?? [],
    surface,
  };
}

/** Verify the downloaded client against what the network advertises. Returns a problem string or null. */
export function clientIntegrity(cfg, live) {
  if (!live.client || live.client.error) return null;
  const mode = cfg.network.clientMustMatch;
  if (mode === 'engine' && live.client.sha256 !== live.engineSha256) return 'served client bundle does not hash to the advertised engine_sha256';
  if (mode === 'release' && live.release?.clientSha256 && live.client.sha256 !== live.release.clientSha256) return 'served client bundle does not match the release manifest client_sha256';
  return null;
}

/** Pure classification from gathered facts (exported for tests). */
export function classify({ moved, failClosed, expectationProblems, surfaceDiff, snapshotStale, integrityProblem }) {
  const reasons = [];
  if (integrityProblem) reasons.push(integrityProblem);
  for (const p of expectationProblems) reasons.push(`network no longer matches what this project expects: ${p}`);
  if (surfaceDiff?.breaking) reasons.push(`client surface changed in ways this project relies on (${surfaceDiff.counts.breaking} breaking change${surfaceDiff.counts.breaking === 1 ? '' : 's'})`);
  if (moved.length && failClosed) reasons.push(`pinned ${moved.join(' and ')} no longer match the network, and this project refuses to run on unpinned values`);
  if (reasons.length) return { classification: 'breaking', exitCode: EXIT.BREAKING, reasons };
  if (moved.length) return { classification: 'needs-update', exitCode: EXIT.NEEDS_UPDATE, reasons: [`pinned ${moved.join(' and ')} moved; no breaking surface change found`] };
  if (snapshotStale) return { classification: 'needs-update', exitCode: EXIT.NEEDS_UPDATE, reasons: ['client bundle changed since the recorded surface snapshot; no breaking surface change found'] };
  return { classification: 'compatible', exitCode: EXIT.COMPATIBLE, reasons: ['pins and client surface match the live network'] };
}

export async function runCheck(cfg, { live, http, withClient } = {}) {
  const snapshot = readSnapshot(cfg);
  const wantClient = withClient ?? (!!cfg.surface || cfg.pins.some((p) => p.tracks === 'client'));
  live = live || await readLive(cfg.network, { http, withClient: wantClient });
  const pinReads = readPins(cfg.root, cfg.pins);
  const { values: pinned, problems: pinProblems } = pinnedValues(pinReads);
  // Projects without explicit pins are compared against the hashes recorded in their snapshot.
  const reference = { ...(snapshot ? { engine: snapshot.engineSha256, params: snapshot.paramsSha256, client: snapshot.clientSha256 } : {}), ...pinned };
  const liveVals = { engine: live.engineSha256, params: live.paramsSha256, client: live.client?.sha256 ?? null };
  const tracked = [...new Set(cfg.pins.filter((p) => !p.replaceAll).map((p) => p.tracks))];
  const moved = tracked.filter((k) => liveVals[k] && pinned[k] && pinned[k] !== liveVals[k]);

  const expectationProblems = [
    ...checkExpectations(live.facts?.value, cfg.network.expectFacts).map((p) => `network facts ${p}`),
    ...(live.status ? checkExpectations(live.status.value, cfg.network.expectStatus).map((p) => `status ${p}`) : []),
  ];
  if (live.chainId !== cfg.network.chainId) expectationProblems.push(`chain id is ${live.chainId}, expected ${cfg.network.chainId}`);

  let surfaceDiff = null, surfaceState = 'not-configured', newSurface = null, snapshotStale = false;
  if (cfg.surface) {
    if (!live.client || live.client.error) surfaceState = 'unknown (client bundle could not be downloaded)';
    else {
      newSurface = extractSurface(new TextDecoder().decode(live.client.bytes), { shapes: cfg.surface.shapes });
      if (!snapshot) surfaceState = 'no snapshot yet';
      else if (snapshot.clientSha256 === live.client.sha256) surfaceState = 'unchanged';
      else {
        surfaceDiff = compareSurfaces(snapshot.surface, newSurface, cfg.surface.uses);
        surfaceState = surfaceDiff.breaking ? 'breaking changes' : 'changed, nothing this project relies on broke';
        snapshotStale = true;
      }
      if (!snapshot) snapshotStale = true;
    }
  }
  if (snapshot && ((live.engineSha256 && snapshot.engineSha256 !== live.engineSha256) || (live.paramsSha256 && snapshot.paramsSha256 !== live.paramsSha256))) snapshotStale = true;
  const integrityProblem = clientIntegrity(cfg, live);
  const verdict = classify({ moved, failClosed: cfg.failClosedOnPinMismatch, expectationProblems, surfaceDiff, snapshotStale, integrityProblem });
  const pinnedEngine = reference.engine;
  return {
    project: cfg.project,
    checkedAt: live.fetchedAt,
    ...verdict,
    live: liveSummary(live),
    pinned: reference,
    pinnedRelease: pinnedEngine ? (releasesForEngine(live.release, pinnedEngine).at(-1)?.version ?? null) : null,
    releasesBehind: pinnedEngine ? releasesSince(live.release, pinnedEngine) : -1,
    moved,
    pinProblems,
    pins: pinReads.map((r) => ({ id: r.pin.id, file: r.pin.file, tracks: r.pin.tracks, value: r.value ?? null, error: r.error ?? null, replaceAll: !!r.replaceAll })),
    expectationProblems,
    integrityProblem,
    surface: { state: surfaceState, diff: surfaceDiff },
    _liveRaw: live,
    _newSurface: newSurface,
    _snapshot: snapshot,
  };
}

export function publicResult(r) {
  const { _liveRaw, _newSurface, _snapshot, ...rest } = r;
  return rest;
}

/** Run test commands sequentially; stop at the first failure. */
export async function runTests(cfg, { spawnImpl = spawn, log = () => {} } = {}) {
  const results = [];
  for (const t of cfg.tests) {
    log(`$ ${t.run}`);
    const started = Date.now();
    const r = await new Promise((resolve) => {
      const child = spawnImpl(t.run, { cwd: path.join(cfg.root, t.cwd || '.'), shell: true, env: { ...process.env, CI: process.env.CI || 'true' } });
      let out = '';
      const keep = (b) => { out = (out + b.toString()).slice(-20000); };
      child.stdout?.on('data', keep);
      child.stderr?.on('data', keep);
      const timer = setTimeout(() => child.kill('SIGKILL'), cfg.testTimeoutMinutes * 60000);
      child.on('close', (code, signal) => { clearTimeout(timer); resolve({ code, signal, out }); });
      child.on('error', (e) => { clearTimeout(timer); resolve({ code: 127, signal: null, out: String(e.message) }); });
    });
    const ok = r.code === 0;
    results.push({ run: t.run, ok, exitCode: r.code, signal: r.signal, seconds: Math.round((Date.now() - started) / 1000), tail: redact(r.out.slice(-3000)) });
    if (!ok) break;
  }
  const passed = results.length === cfg.tests.length && results.every((r) => r.ok);
  return { configured: cfg.tests.length, passed, results };
}

export function appendEvidence(cfg, entry, keep = 50) {
  const f = path.join(cfg.root, cfg.evidence);
  let doc = { note: 'Generated by poa-compat. Evidence for each PoA core update applied to this project.', entries: [] };
  if (fs.existsSync(f)) { try { doc = JSON.parse(fs.readFileSync(f, 'utf8')); } catch { /* rewrite */ } }
  doc.entries = [...(doc.entries || []), entry].slice(-keep);
  fs.mkdirSync(path.dirname(f), { recursive: true });
  fs.writeFileSync(f, JSON.stringify(doc, null, 2) + '\n');
  return cfg.evidence;
}

/** Apply live values to every declared pin, refresh the surface snapshot, record evidence, run tests. */
export async function runUpdate(cfg, { http, live, skipTests = false, force = false, log = () => {}, spawnImpl } = {}) {
  const check = await runCheck(cfg, { live, http });
  const L = check._liveRaw;
  if (check.classification === 'compatible' && !force) return { check, updated: false, changedFiles: [], tests: { configured: cfg.tests.length, passed: true, results: [], skipped: true }, notes: [] };
  const refuse = [];
  if (!HEX64.test(L.engineSha256 || '') || !HEX64.test(L.paramsSha256 || '')) refuse.push('live engine/params hashes are not valid sha256 values');
  if (L.chainId !== cfg.network.chainId) refuse.push(`live chain id ${L.chainId} is not ${cfg.network.chainId}`);
  if (check.integrityProblem) refuse.push(check.integrityProblem);
  if (check.pinProblems.length) refuse.push(...check.pinProblems);
  if (refuse.length) { const e = new Error(`refusing to update: ${refuse.join('; ')}`); e.check = check; throw e; }

  const to = { engine: L.engineSha256, params: L.paramsSha256, client: L.client?.sha256 || undefined };
  const { changed, notes } = writePins(cfg.root, cfg.pins, check.pinned, to);
  const changedFiles = [...changed];
  if (cfg.surface && check._newSurface) {
    const f = path.join(cfg.root, cfg.surface.snapshot);
    fs.mkdirSync(path.dirname(f), { recursive: true });
    const next = JSON.stringify(makeSnapshot(L, check._newSurface), null, 2) + '\n';
    const prev = fs.existsSync(f) ? fs.readFileSync(f, 'utf8') : '';
    const strip = (s) => s.replace(/"capturedAt": "[^"]*",?/, '');
    if (strip(prev) !== strip(next)) { fs.writeFileSync(f, next); changedFiles.push(cfg.surface.snapshot); }
  } else if (cfg.surface) notes.push('surface snapshot not refreshed: client bundle unavailable');

  const evidence = {
    at: L.fetchedAt,
    classification: check.classification,
    reasons: check.reasons,
    from: { engine: check.pinned.engine ?? null, params: check.pinned.params ?? null, client: check._snapshot?.clientSha256 ?? check.pinned.client ?? null, release: check.pinnedRelease },
    to: { engine: L.engineSha256, params: L.paramsSha256, client: L.client?.sha256 ?? null, clientSize: L.client?.size ?? null, clientLastModified: L.client?.lastModified ?? null, release: L.release?.version ?? null, releaseTxid: L.release?.txid ?? null },
    sources: { facts: L.facts?.url, release: L.release?.url ?? null, client: L.client?.url ?? null },
    surface: check.surface.diff ? { counts: check.surface.diff.counts, breaking: check.surface.diff.changes.filter((c) => c.severity === 'breaking').map((c) => c.detail) } : { state: check.surface.state },
    files: changedFiles.slice(),
  };
  if (changedFiles.length) changedFiles.push(appendEvidence(cfg, evidence));
  const tests = skipTests ? { configured: cfg.tests.length, passed: false, skipped: true, results: [] } : await runTests(cfg, { log, spawnImpl });
  return { check, updated: changedFiles.length > 0, changedFiles: [...new Set(changedFiles)], tests, notes, evidence };
}
