// Branch + pull request through git and the GitHub CLI. Tokens come from the environment (GH_TOKEN);
// they are never passed on a command line or printed.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { scanFiles } from './secret-scan.mjs';

export function defaultRunner(root) {
  return (cmd, args, { allowFail = false, input } = {}) => {
    try {
      return execFileSync(cmd, args, { cwd: root, encoding: 'utf8', stdio: ['pipe', 'pipe', 'pipe'], input }).trim();
    } catch (e) {
      if (allowFail) return null;
      const msg = (e.stderr || e.message || '').toString().split('\n').slice(0, 5).join(' ');
      throw new Error(`${cmd} ${args[0]} failed: ${msg}`);
    }
  };
}

/** Decide whether auto-merge may be enabled, with a plain reason either way. */
export function autoMergeDecision(report, { when = 'never', allowUnknownSurface = false } = {}) {
  if (when === 'never') return { enable: false, reason: 'Auto-merge is off for this project; a person reviews and merges.' };
  if (when !== 'breaking') return { enable: false, reason: `Unknown auto-merge policy "${when}"; leaving for review.` };
  if (report.check.classification !== 'breaking') return { enable: false, reason: 'Not breaking: the app still works, so this waits for a person to review and merge.' };
  if (report.check.surface?.diff?.breaking) return { enable: false, reason: 'The client surface changed in ways this project relies on. Updating pins alone may not be enough, so a person must review the code before merging.' };
  if (report.check.expectationProblems?.length) return { enable: false, reason: 'The network no longer matches values this project expects; a person must review.' };
  if (!report.tests.configured) return { enable: false, reason: 'Breaking, but no test commands are configured, so this waits for review.' };
  if (!report.tests.passed) return { enable: false, reason: 'Breaking, but the configured tests did not all pass, so this waits for review.' };
  if (report.check.surface.state.startsWith('unknown') && !allowUnknownSurface) return { enable: false, reason: 'Breaking, but the client bundle could not be checked, so this waits for review.' };
  if (report.check.integrityProblem) return { enable: false, reason: 'The served client did not match what the network advertises; leaving for review.' };
  return { enable: true, reason: 'Breaking and every configured test passed: auto-merge (squash) is enabled. It completes once the repository\'s required checks pass.' };
}

export function titleFor(report, prefix) {
  const L = report.check.live;
  const tag = report.check.classification === 'breaking' ? 'breaking' : 'update';
  return `${prefix}: ${tag}, engine ${String(L.engineSha256).slice(0, 8)} / params ${String(L.paramsSha256).slice(0, 8)}${L.release?.version ? ` (${L.release.version})` : ''}`;
}

export function openPr({ cfg, report, body, when = 'never', dispatchWorkflow, dryRun = false, run = defaultRunner(cfg.root), log = () => {}, commitName, commitEmail }) {
  const files = report.changedFiles || [];
  if (!files.length) return { skipped: true, reason: 'nothing changed' };
  const hits = scanFiles(cfg.root, files);
  if (hits.length) throw new Error(`secret scan blocked the push: ${hits.map((h) => `${h.file}:${h.line}`).join(', ')}`);
  const decision = autoMergeDecision(report, { when, allowUnknownSurface: cfg.pr.allowUnknownSurface });
  const title = titleFor(report, cfg.pr.titlePrefix);
  const branch = cfg.pr.branch;
  const plan = [];
  const step = (cmd, args, opts) => { plan.push([cmd, ...args].join(' ')); return dryRun ? '' : run(cmd, args, opts); };
  const bodyFile = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'poa-compat-')), 'body.md');
  fs.writeFileSync(bodyFile, `${body}\n\n### Merge\n${decision.reason}\n`);

  const name = commitName || process.env.POA_COMPAT_GIT_NAME || 'poa-compat';
  const email = commitEmail || process.env.POA_COMPAT_GIT_EMAIL || 'poa-compat@users.noreply.github.com';
  step('git', ['checkout', '-B', branch]);
  step('git', ['add', '--', ...files]);
  step('git', ['-c', `user.name=${name}`, '-c', `user.email=${email}`, 'commit', '-m', title, '-m', 'Generated by poa-compat from the public PoA network facts, release manifest and client bundle.']);
  step('git', ['push', '--force', 'origin', `HEAD:refs/heads/${branch}`]);
  const existing = dryRun ? '[]' : run('gh', ['pr', 'list', '--head', branch, '--base', cfg.pr.base, '--state', 'open', '--json', 'number,url'], { allowFail: true }) || '[]';
  let pr = JSON.parse(existing)[0];
  if (pr) step('gh', ['pr', 'edit', String(pr.number), '--title', title, '--body-file', bodyFile]);
  else {
    const args = ['pr', 'create', '--base', cfg.pr.base, '--head', branch, '--title', title, '--body-file', bodyFile];
    for (const l of cfg.pr.labels) args.push('--label', l);
    if (cfg.pr.draft && !decision.enable) args.push('--draft');
    const url = step('gh', args);
    pr = { url: url || '(dry run)', number: Number((url || '').split('/').pop()) || null };
  }
  if (dispatchWorkflow) step('gh', ['workflow', 'run', dispatchWorkflow, '--ref', branch]);
  if (pr.number) {
    if (decision.enable) step('gh', ['pr', 'merge', String(pr.number), '--auto', '--squash']);
    else step('gh', ['pr', 'merge', String(pr.number), '--disable-auto'], { allowFail: true });
  }
  return { pr, title, branch, autoMerge: decision, plan };
}
